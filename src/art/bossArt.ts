export function bossCanvas(k: string): HTMLCanvasElement {
  const A = BOSS_ART[k], c = document.createElement('canvas'); c.width = Math.max(...A.r.map(r => r.length)); c.height = A.r.length;
  const g = c.getContext('2d');
  A.r.forEach((row, y) => { for (let x = 0; x < row.length; x++) { const col = A.p[row[x]]; if (col) { g.fillStyle = col; g.fillRect(x, y, 1, 1); } } });
  return c;
}
